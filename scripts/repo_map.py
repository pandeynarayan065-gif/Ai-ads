#!/usr/bin/env python3
"""Write REPO_MAP.md: a compact map of this workspace, so a session can find things without searching.

For every folder (fonts, caches and .git skipped): its scripts with the first line of their docstring, its notes and
prompt files with their first line, and a count of its media (videos, images). Re-run after adding work:

  python3 scripts/repo_map.py
"""
import ast
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SKIP = {".git", "__pycache__", "fonts", "node_modules", ".claude"}
MEDIA = {".mp4", ".mov", ".png", ".jpg", ".jpeg", ".wav", ".pdf", ".webp"}
DOCS = {".md", ".txt"}


def first_line_py(p):
    try:
        doc = ast.get_docstring(ast.parse(p.read_text(errors="ignore")))
    except SyntaxError:
        doc = None
    if doc:
        return doc.strip().splitlines()[0]
    for line in p.read_text(errors="ignore").splitlines()[:5]:
        if line.startswith("//") or line.startswith("#") and not line.startswith("#!"):
            return line.lstrip("/# ").strip()
    return ""


def first_line_doc(p):
    for line in p.read_text(errors="ignore").splitlines():
        s = line.strip().lstrip("#").strip()
        if s:
            return s[:110]
    return ""


def main():
    out = ["# Repo map", "",
           "Generated by `python3 scripts/repo_map.py`. Read this to find files instead of searching. Media is counted, "
           "not listed (use `ls` on the folder).", "",
           "```mermaid",
           "flowchart LR",
           "  B[brand/&lt;brand&gt;.md + product-lock + preferences] --> R[brief / plan.md]",
           "  R --> P[prompt-*.md / motion-*.md]",
           "  P -->|prompt_lint.py + dry run + OK| K[kie_generate.py: Nano Banana / Seedance]",
           "  K --> T[takes/ clips/ images/]",
           "  T --> F[post: edit / label fix / esrgan_upscale / finish_film / end card]",
           "  F --> D[deliverable .mp4 / .png]",
           "  T --> L[prompt-log.md + shot card]",
           "```", ""]
    dirs = sorted({p.parent for p in ROOT.rglob("*") if p.is_file()
                   and not any(part in SKIP for part in p.relative_to(ROOT).parts)})
    for d in dirs:
        rel = d.relative_to(ROOT)
        files = sorted(f for f in d.iterdir() if f.is_file())
        scripts = [f for f in files if f.suffix in (".py", ".js")]
        docs = [f for f in files if f.suffix in DOCS]
        media = [f for f in files if f.suffix.lower() in MEDIA]
        if not (scripts or docs or media):
            continue
        out.append(f"## {rel if str(rel) != '.' else '(root)'}")
        for f in scripts:
            out.append(f"- `{f.name}`: {first_line_py(f)}")
        for f in docs:
            out.append(f"- `{f.name}`: {first_line_doc(f)}")
        if media:
            kinds = {}
            for f in media:
                kinds[f.suffix.lower()] = kinds.get(f.suffix.lower(), 0) + 1
            finals = [f.name for f in media if f.suffix == ".mp4" and not f.parent.name in ("takes", "clips")
                      and f.name.startswith(("spraymax-", "misfits-"))]
            line = "- media: " + ", ".join(f"{n} {k}" for k, n in sorted(kinds.items()))
            if finals:
                line += "; deliverables: " + ", ".join(f"`{x}`" for x in finals)
            out.append(line)
        out.append("")
    (ROOT / "REPO_MAP.md").write_text("\n".join(out))
    print(f"wrote REPO_MAP.md: {len(dirs)} folders, {sum(1 for l in out if l.startswith('- '))} entries")


if __name__ == "__main__":
    main()
